/**
 * Emits JSON Schema (`schema/`) and TypeScript declarations (`types/`) from the Zod schemas in
 * `src/2014/schemas/`, which stay the single source of truth, and the id list of every collection
 * (`ids/`) from the English data, plus `ids/published.json`, the ever-growing set of ids ever published.
 *
 *   pnpm run generate         write the files
 *   pnpm run generate:check   fail if any committed file is stale, missing, or orphaned
 *
 * Output is deterministic: no timestamps, a fixed file order, a trailing newline, and the JSON
 * Schema key order that Zod produces.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';
import { z } from 'zod';
import {
  loadCollections,
  loadDerivedCollections,
  publishedIds,
  sortedIndices,
  HAND_WRITTEN_IDS_FILES,
} from './ids';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schemasDir = path.join(root, 'src/2014/schemas');
const jsonSchemaDir = path.join(root, 'schema');
const typesDir = path.join(root, 'types');
const idsDir = path.join(root, 'ids');

const HEADER =
  'Generated by scripts/generate-schemas.ts from src/2014/schemas. Do not edit by hand.';

export type GeneratedFiles = Map<string, string>;

/** `5e-SRD-Ability-Scores.ts` -> `5e-SRD-Ability-Scores` */
function baseName(file: string): string {
  return file.replace(/\.ts$/, '');
}

/** `AbilityScoreSchema` -> `AbilityScore` */
function typeName(exportName: string): string {
  return exportName.replace(/Schema$/, '');
}

function schemaFiles(): string[] {
  return fs
    .readdirSync(schemasDir)
    .filter((f) => f.endsWith('.ts'))
    .sort();
}

/** The one exported Zod schema in a module (each schema file exports exactly one). */
function findSchema(
  file: string,
  mod: Record<string, unknown>
): { exportName: string; schema: z.ZodType } {
  const entries = Object.entries(mod).filter(([, v]) => v instanceof z.ZodType);
  if (entries.length !== 1) {
    throw new Error(`${file}: expected exactly one exported Zod schema, found ${entries.length}`);
  }
  const [exportName, schema] = entries[0] as [string, z.ZodType];
  return { exportName, schema };
}

function printTypes(entries: { file: string; exportName: string }[]): Map<string, string> {
  const virtual = path.join(root, '__generate-types.ts');
  const source = [
    "import type { z } from 'zod';",
    ...entries.map(
      (e) =>
        `import type { ${e.exportName} } from './src/2014/schemas/${baseName(e.file)}';\n` +
        `type ${typeName(e.exportName)} = z.infer<typeof ${e.exportName}>;`
    ),
  ].join('\n');

  const options: ts.CompilerOptions = {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    strict: true,
    skipLibCheck: true,
    noEmit: true,
    types: [],
  };
  const host = ts.createCompilerHost(options);
  const readFile = host.readFile.bind(host);
  const fileExists = host.fileExists.bind(host);
  const getSourceFile = host.getSourceFile.bind(host);
  host.fileExists = (f) => f === virtual || fileExists(f);
  host.readFile = (f) => (f === virtual ? source : readFile(f));
  host.getSourceFile = (f, lang, ...rest) =>
    f === virtual ? ts.createSourceFile(f, source, lang, true) : getSourceFile(f, lang, ...rest);

  const program = ts.createProgram([virtual], options, host);
  const errors = ts.getPreEmitDiagnostics(program).filter((d) => d.file?.fileName === virtual);
  if (errors.length) {
    throw new Error(ts.formatDiagnostics(errors, host));
  }

  const checker = program.getTypeChecker();
  const sourceFile = program.getSourceFile(virtual)!;
  const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed });
  const flags =
    ts.NodeBuilderFlags.NoTruncation |
    ts.NodeBuilderFlags.InTypeAlias |
    ts.NodeBuilderFlags.MultilineObjectLiterals;

  const out = new Map<string, string>();
  for (const stmt of sourceFile.statements) {
    if (!ts.isTypeAliasDeclaration(stmt)) continue;
    const node = checker.typeToTypeNode(checker.getTypeAtLocation(stmt.name), stmt, flags)!;
    const name = stmt.name.text;
    const alias = ts.factory.createTypeAliasDeclaration(
      [ts.factory.createModifier(ts.SyntaxKind.ExportKeyword)],
      name,
      undefined,
      node
    );
    out.set(name, printer.printNode(ts.EmitHint.Unspecified, alias, sourceFile));
  }
  return out;
}

export async function generate(): Promise<GeneratedFiles> {
  const files: GeneratedFiles = new Map();
  const entries: { file: string; exportName: string; schema: z.ZodType }[] = [];

  for (const file of schemaFiles()) {
    const mod = await import(pathToFileURL(path.join(schemasDir, file)).href);
    entries.push({ file, ...findSchema(file, mod) });
  }

  const types = printTypes(entries);
  for (const { file, exportName, schema } of entries) {
    const base = baseName(file);
    const jsonSchema = z.toJSONSchema(schema);
    files.set(`schema/${base}.schema.json`, `${JSON.stringify(jsonSchema, null, 2)}\n`);
    // The default export types the data file that the package's `exports` entry for this collection serves.
    const name = typeName(exportName);
    files.set(
      `types/${base}.d.ts`,
      `// ${HEADER}\n\n${types.get(name)}\n\ndeclare const data: ${name}[];\nexport default data;\n`
    );
  }
  const idCollections = [...loadCollections(), ...loadDerivedCollections()];
  for (const collection of idCollections) {
    const list = { collection: collection.name, indices: sortedIndices(collection) };
    files.set(`ids/${collection.name}.json`, `${JSON.stringify(list, null, 2)}\n`);
  }
  files.set('ids/published.json', `${JSON.stringify(publishedIds(idCollections), null, 2)}\n`);
  return files;
}

function existingGenerated(): string[] {
  const list = (dir: string, ext: string) =>
    fs.existsSync(dir)
      ? fs
          .readdirSync(dir)
          .filter((f) => f.endsWith(ext))
          .map((f) => `${path.basename(dir)}/${f}`)
      : [];
  return [...list(jsonSchemaDir, '.json'), ...list(typesDir, '.d.ts'), ...list(idsDir, '.json')]
    .filter((rel) => !HAND_WRITTEN_IDS_FILES.includes(rel))
    .sort();
}

/** Returns a human-readable list of problems; empty when everything is up to date. */
export function diff(files: GeneratedFiles): string[] {
  const problems: string[] = [];
  for (const [rel, content] of files) {
    const abs = path.join(root, rel);
    if (!fs.existsSync(abs)) problems.push(`missing: ${rel}`);
    else if (fs.readFileSync(abs, 'utf8') !== content) problems.push(`stale: ${rel}`);
  }
  for (const rel of existingGenerated()) {
    if (!files.has(rel)) problems.push(`orphaned: ${rel}`);
  }
  return problems;
}

function write(files: GeneratedFiles): void {
  for (const rel of existingGenerated()) {
    if (!files.has(rel)) fs.rmSync(path.join(root, rel));
  }
  for (const [rel, content] of files) {
    const abs = path.join(root, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = await generate();
  if (process.argv.includes('--check')) {
    const problems = diff(files);
    if (problems.length) {
      console.error(
        `Generated files are out of date:\n${problems.map((p) => `  ${p}`).join('\n')}`
      );
      console.error('Run "pnpm run generate" and commit the result.');
      process.exit(1);
    }
    console.log(`Generated files are up to date (${files.size} files).`);
  } else {
    write(files);
    console.log(`Wrote ${files.size} files to schema/, types/ and ids/.`);
  }
}
